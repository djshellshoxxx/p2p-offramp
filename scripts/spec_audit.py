#!/usr/bin/env python3
"""Inventory specification readiness. Structure is evidence, never approval."""
from __future__ import annotations
import argparse
from collections import Counter
from dataclasses import asdict, dataclass
import json
from pathlib import Path
import re
from urllib.parse import unquote, urlsplit


@dataclass(frozen=True)
class Spec:
    path: str
    status: str
    category: str
    missing_sections: list[int]
    broken_links: list[str]


def prose(text: str) -> str:
    """Exclude fenced examples from metadata and heading checks."""
    lines, fence, marker, width = [], False, '', 0
    for line in text.splitlines():
        m = re.match(r'^\s*(`{3,}|~{3,})', line)
        if m:
            if not fence:
                fence, marker, width = True, m.group(1)[0], len(m.group(1))
            elif m.group(1)[0] == marker and len(m.group(1)) >= width:
                fence = False
            continue
        if not fence:
            lines.append(line)
    return '\n'.join(lines)


def inspect(root: Path, path: Path) -> Spec:
    body = prose(path.read_text(encoding='utf-8'))
    match = re.search(r'(?im)^\s*(?:-\s*)?(?:\*\*)?Status:(?:\*\*)?\s*(.+)$', body)
    if not match:
        match = re.search(r'(?im)^\|\s*Status\s*\|\s*([^|]+)\|\s*$', body)
    status = match.group(1).strip() if match else 'Missing explicit status'
    lowered = status.lower()
    if path.name == 'spec-master-specification-index.md':
        category = 'catalog'
    elif 'placeholder' in lowered or 'scaffold' in lowered:
        category = 'scaffold'
    elif 'outline' in lowered:
        category = 'outline'
    elif 'planning' == lowered or lowered.startswith('planning,'):
        category = 'planning'
    elif any(word in lowered for word in ('baseline', 'expanded', 'design complete', 'detailed engineering specification')):
        category = 'design-review-pending'
    else:
        category = 'manual-review-needed'
    present = {int(n) for n in re.findall(r'^##\s+([1-7])\.\s+', body, re.M)}
    broken = []
    for link in re.findall(r'\[[^\]\n]*\]\(([^\s)]+)(?:\s+"[^"\n]*")?\)', body):
        url = urlsplit(link)
        if url.scheme or url.netloc or not url.path:
            continue
        target = (path.parent / unquote(url.path)).resolve()
        if not target.is_relative_to(root.resolve()) or not target.exists():
            broken.append(link)
    return Spec(path.relative_to(root).as_posix(), status, category,
                sorted(set(range(1, 8)) - present), sorted(set(broken)))


def audit(root: Path) -> list[Spec]:
    return [inspect(root, p) for p in sorted(root.glob('[0-9][0-9]_*/**/spec-*.md'))]


def unindexed(root: Path, specs: list[Spec]) -> list[str]:
    catalogs = [root / s.path for s in specs if s.category == 'catalog']
    targets = set()
    for catalog in catalogs:
        for link in re.findall(r'\]\(([^\s)]+)\)', prose(catalog.read_text(encoding='utf-8'))):
            url = urlsplit(link)
            if not url.scheme and not url.netloc and url.path:
                targets.add((catalog.parent / unquote(url.path)).resolve())
    return [s.path for s in specs if s.category != 'catalog' and (root / s.path).resolve() not in targets]


def render(specs: list[Spec]) -> str:
    counts = Counter(s.category for s in specs)
    lines = ['# Specification readiness inventory', '',
             'Generated by `python scripts/spec_audit.py --markdown docs/SPEC_READINESS.md`.', '',
             f'Total: **{len(specs)}** specifications. No document is automatically certified complete.', '',
             '| Category | Count |', '|---|---:|']
    lines += [f'| {key} | {value} |' for key, value in sorted(counts.items())]
    lines += ['', 'A numbered section check detects structure only. Semantic correctness, protocol interoperability,',
              'implementation evidence, and independent security review still require review. Catalogs and planning',
              'documents are inventoried but do not need the seven technical sections. Link checks validate local',
              'file targets; remote URLs, reference-style links, and heading fragments require separate review.', '',
              '| Specification | Category | Missing numbered sections | Broken local links |', '|---|---|---|---|']
    for spec in specs:
        link = '../' + spec.path
        lines.append(f'| [{spec.path}]({link}) | {spec.category} | ' +
                     (', '.join(map(str, spec.missing_sections)) or 'none') +
                     f' | {len(spec.broken_links)} |')
    return '\n'.join(lines) + '\n'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--markdown', type=Path)
    parser.add_argument('--json', action='store_true')
    parser.add_argument('--check', action='store_true', help='Fail on unexpanded specs, malformed structure, or broken links')
    parser.add_argument('--check-links', action='store_true', help='Check local file links and catalog coverage only; does not certify readiness')
    args = parser.parse_args()
    specs = audit(args.root.resolve())
    uncovered = unindexed(args.root.resolve(), specs)
    if args.markdown:
        args.markdown.parent.mkdir(parents=True, exist_ok=True)
        args.markdown.write_text(render(specs), encoding='utf-8')
    if args.json:
        print(json.dumps([asdict(s) for s in specs], indent=2))
    else:
        print(json.dumps({'total': len(specs), 'categories': dict(Counter(s.category for s in specs)),
                          'broken_links': sum(len(s.broken_links) for s in specs),
                          'unindexed': uncovered}, sort_keys=True))
    incomplete = not specs or bool(uncovered) or any(s.broken_links or s.category in {'scaffold', 'outline', 'manual-review-needed'} or
        (s.category not in {'catalog', 'planning'} and s.missing_sections) for s in specs)
    broken = bool(uncovered) or any(s.broken_links for s in specs) or not specs
    return int((args.check and incomplete) or (args.check_links and broken))


if __name__ == '__main__':
    raise SystemExit(main())
